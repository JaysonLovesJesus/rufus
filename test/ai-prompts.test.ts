import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { CorpusStore, aiPromptsAdapter, collectInto, getAdapter, tagPrompt } from '../src';
import { main } from '../src/cli';
import { tempDir } from './helpers';

const jsonl = (rows: unknown[]): string => rows.map((r) => JSON.stringify(r)).join('\n');

/** An item as JSON, minus the labeled `priorProposal` / `context` metadata (the only place a preceding assistant turn may appear). */
const withoutProposalContext = (i: { metadata?: Record<string, unknown> }): string => {
  const { priorProposal: _p, context: _c, ...metadata } = i.metadata ?? {};
  return JSON.stringify({ ...i, metadata });
};

describe('ai-prompts adapter', () => {
  it('is registered, so `rufus collect ai-prompts` resolves', () => {
    expect(getAdapter('ai-prompts')).toBe(aiPromptsAdapter);
  });

  it('keeps ONLY human messages: assistant, model, system and tool replies never enter the corpus', async () => {
    const dir = await tempDir();
    const file = path.join(dir, 'chat.jsonl');
    await writeFile(
      file,
      jsonl([
        { role: 'system', content: 'You are a helpful assistant.', timestamp: '2026-03-01T10:00:00Z', threadId: 't1' },
        { role: 'user', content: 'Plan my week around the launch.', timestamp: '2026-03-01T10:01:00Z', threadId: 't1' },
        { role: 'assistant', content: 'Certainly! Here is a delightful plan with synergy.', timestamp: '2026-03-01T10:02:00Z', threadId: 't1' },
        { role: 'model', content: 'Gemini-style reply that must never be stored.', timestamp: '2026-03-01T10:02:30Z', threadId: 't1' },
        { role: 'tool', content: 'search results blob', timestamp: '2026-03-01T10:03:00Z', threadId: 't1' },
        { type: 'assistant_message', text: 'Another model line.', timestamp: '2026-03-01T10:04:00Z' },
        { type: 'user_message', text: "No, that's too complicated. Keep it to three items.", timestamp: '2026-03-01T10:05:00Z', threadId: 't1' },
        { createdBy: 'user', text: "Let's go with the short version.", timestamp: '2026-03-01T10:06:00Z', threadId: 't1' },
        { createdBy: 'assistant', text: 'Great choice!', timestamp: '2026-03-01T10:07:00Z', threadId: 't1' },
        { role: 'user', content: '   ', timestamp: '2026-03-01T10:08:00Z' },
        { text: 'No author signal at all: dropped rather than guessed.', timestamp: '2026-03-01T10:09:00Z' },
        { role: 'assistant', type: 'user_message', text: 'Contradictory author: rejected.', timestamp: '2026-03-01T10:10:00Z' },
      ]),
    );
    const items = await aiPromptsAdapter.collect({ path: file });
    expect(items.map((i) => i.summary).sort()).toEqual(["Let's go with the short version.", "No, that's too complicated. Keep it to three items.", 'Plan my week around the launch.']);
    for (const i of items) {
      expect(i.source).toBe('ai-prompts');
      expect(withoutProposalContext(i)).not.toMatch(/Certainly|synergy|Gemini-style|search results|Another model|Great choice|Contradictory|No author signal/);
    }
  });

  it('reads { messages: [...] } conversations, wrapped message bodies and text-part arrays; ignores tool results and injected wrappers', async () => {
    const dir = await tempDir();
    const file = path.join(dir, 'export.json');
    await writeFile(
      file,
      JSON.stringify([
        {
          id: 'conv-9',
          messages: [
            { role: 'user', content: [{ type: 'text', text: 'First part.' }, { type: 'tool_result', content: 'LEAKED TOOL OUTPUT' }, { type: 'text', text: 'Second part?' }], created_at: '2026-04-01T09:00:00Z' },
            { role: 'assistant', content: [{ type: 'text', text: 'Assistant prose' }] },
            { role: 'user', content: '<system-reminder>injected boilerplate</system-reminder>', created_at: '2026-04-01T09:01:00Z' },
            { role: 'user', content: '<system-reminder>injected</system-reminder> Real words here.', created_at: '2026-04-01T09:02:00Z' },
            { type: 'user', message: { role: 'user', content: 'Wrapped line.' }, timestamp: '2026-04-01T09:03:00Z' },
            { type: 'assistant', message: { role: 'assistant', content: 'Wrapped assistant.' }, timestamp: '2026-04-01T09:04:00Z' },
            { role: 'user', content: 'Caveat: The messages below were generated by the user while running local commands. DO NOT respond.' },
          ],
        },
        { mapping: { a: { message: { author: { role: 'user' }, content: { parts: ['Export style prompt.'] }, create_time: 1775034000 } }, b: { message: { author: { role: 'assistant' }, content: { parts: ['Export style reply.'] } } } } },
      ]),
    );
    const items = await aiPromptsAdapter.collect({ path: file });
    const text = items.map((i) => i.summary);
    expect(text.sort()).toEqual(['Export style prompt.', 'First part. Second part?', 'Real words here.', 'Wrapped line.']);
    expect(items.map(withoutProposalContext).join('')).not.toMatch(/LEAKED|Assistant|injected|Export style reply|Caveat/);
    expect(JSON.stringify(items)).not.toMatch(/LEAKED|injected|Export style reply|Caveat/);
    expect(items.find((i) => i.summary.startsWith('First'))!.metadata).toEqual({ threadId: 'conv-9' });
  });

  it('tags pushback/correction, decision and question deterministically, and sets kind by priority', () => {
    expect(tagPrompt("No, that's not what I meant.")).toEqual({ kind: 'pushback', tags: ['pushback', 'correction'] });
    expect(tagPrompt('Actually, use the older approach.').kind).toBe('pushback');
    expect(tagPrompt("Please don't add a dependency.").kind).toBe('pushback');
    expect(tagPrompt('stop adding comments').kind).toBe('pushback');
    expect(tagPrompt('Use a map instead of a list.').kind).toBe('pushback');
    expect(tagPrompt('This is too complicated.').kind).toBe('pushback');
    expect(tagPrompt('Wrong idea entirely.').kind).toBe('pushback');
    expect(tagPrompt("Let's ship it on Friday.")).toEqual({ kind: 'decision', tags: ['decision'] });
    expect(tagPrompt('Go with option B.').kind).toBe('decision');
    expect(tagPrompt('We should cache this.').kind).toBe('decision');
    expect(tagPrompt('I want to rename the module.').kind).toBe('decision');
    expect(tagPrompt('What does this do?')).toEqual({ kind: 'question', tags: ['question'] });
    expect(tagPrompt("Let's do it, but why is it slow?")).toEqual({ kind: 'decision', tags: ['decision', 'question'] });
    expect(tagPrompt("Don't do that, why would you?").tags).toEqual(['pushback', 'correction', 'question']);
    expect(tagPrompt('Summarize the notes below.')).toEqual({ kind: 'prompt', tags: [] });
    // "no" inside a word or "know" must not fire
    expect(tagPrompt('I know the notation is nominal.').kind).toBe('prompt');
  });

  it('stores kind, tags, timestamp and the human\'s own words as CorpusItems', async () => {
    const dir = await tempDir();
    const file = path.join(dir, 'c.jsonl');
    await writeFile(file, jsonl([{ role: 'user', content: 'Why is this slow? Instead of polling, use events.', timestamp: 1775034000000, threadId: 'x' }]));
    const [item] = await aiPromptsAdapter.collect({ path: file });
    expect(item).toMatchObject({
      source: 'ai-prompts',
      kind: 'pushback',
      summary: 'Why is this slow? Instead of polling, use events.',
      tags: ['pushback', 'correction', 'question'],
      timestamp: new Date(1775034000000).toISOString(),
      metadata: { threadId: 'x' },
    });
  });

  it('dedupes repeated messages in one run and across collects, but keeps the same words in different threads', async () => {
    const dir = await tempDir();
    const a = path.join(dir, 'a.jsonl');
    const b = path.join(dir, 'b.jsonl');
    const row = { role: 'user', content: 'Go with plan B.', timestamp: '2026-05-01T08:00:00Z', threadId: 't1' };
    await writeFile(a, jsonl([row, row, { ...row, content: '  go   with plan B.  ' }, { ...row, threadId: 't2' }]));
    await writeFile(b, jsonl([row]));
    const items = await aiPromptsAdapter.collect({ path: a, extraPaths: [b] });
    expect(items).toHaveLength(2);

    const store = new CorpusStore(path.join(dir, 'corpus.jsonl'));
    const first = await collectInto(store, aiPromptsAdapter, { path: a });
    expect(first.report.added).toBe(2);
    const again = await collectInto(store, aiPromptsAdapter, { path: a });
    expect(again.report).toMatchObject({ added: 0, unchanged: 2, total: 2 });
  });

  it('reads a folder of exports, honors --limit (newest first), and errors clearly on a missing path', async () => {
    const dir = await tempDir();
    await mkdir(path.join(dir, 'exports'));
    await writeFile(path.join(dir, 'exports', '1.jsonl'), jsonl([{ role: 'user', content: 'Old one.', timestamp: '2026-01-01T00:00:00Z' }]));
    await writeFile(path.join(dir, 'exports', '2.json'), JSON.stringify({ threadId: 'z', messages: [{ role: 'user', content: 'New one.', timestamp: '2026-02-01T00:00:00Z' }] }));
    await writeFile(path.join(dir, 'exports', 'notes.txt'), 'ignored');
    const all = await aiPromptsAdapter.collect({ path: path.join(dir, 'exports') });
    expect(all.map((i) => i.summary)).toEqual(['New one.', 'Old one.']);
    expect((await aiPromptsAdapter.collect({ path: path.join(dir, 'exports'), limit: 1 })).map((i) => i.summary)).toEqual(['New one.']);
    await expect(aiPromptsAdapter.collect({ path: path.join(dir, 'nope') })).rejects.toThrow(/Path not found/);
  });

  it('works end to end through `rufus collect ai-prompts <path...>`, with several paths', async () => {
    const dir = await tempDir();
    const a = path.join(dir, 'a.jsonl');
    const b = path.join(dir, 'b.jsonl');
    await writeFile(a, jsonl([{ role: 'user', content: 'Alpha prompt.', timestamp: '2026-05-01T08:00:00Z' }, { role: 'assistant', content: 'Alpha reply.', timestamp: '2026-05-01T08:01:00Z' }]));
    await writeFile(b, jsonl([{ role: 'user', content: 'Beta prompt?', timestamp: '2026-05-02T08:00:00Z' }]));
    const lines: string[] = [];
    const io = { out: (l: string) => void lines.push(l), err: (l: string) => void lines.push(l) };
    await main(['--dir', path.join(dir, 'ws'), 'collect', 'ai-prompts', a, b], io);
    expect(lines.join('\n')).toMatch(/Read 2 item\(s\) from ai-prompts/);
    const stored = await readFile(path.join(dir, 'ws', 'corpus', 'items.jsonl'), 'utf8');
    expect(stored).toContain('Alpha prompt.');
    expect(stored).toContain('Beta prompt?');
    expect(stored).not.toContain('Alpha reply');
  });

  describe('priorProposal context', () => {
    it('attaches the immediately preceding assistant turn to the human reply as context, never as an item', async () => {
      const dir = await tempDir();
      const file = path.join(dir, 'c.jsonl');
      await writeFile(
        file,
        jsonl([
          { role: 'user', content: 'Plan the launch checklist.', timestamp: '2026-03-01T10:00:00Z', threadId: 't1' },
          { role: 'assistant', content: 'Here is a 14-step rollout with a phased canary, feature flags per region and a weekly review board.', timestamp: '2026-03-01T10:01:00Z', threadId: 't1' },
          { role: 'user', content: "No, that's too complicated. Three steps.", timestamp: '2026-03-01T10:02:00Z', threadId: 't1' },
          { role: 'user', content: 'Also add a rollback note.', timestamp: '2026-03-01T10:03:00Z', threadId: 't1' },
        ]),
      );
      const items = await aiPromptsAdapter.collect({ path: file });
      expect(items).toHaveLength(3); // the assistant turn is not an item
      const byText = (t: string) => items.find((i) => i.summary.startsWith(t))!;

      const pushback = byText("No, that's too complicated");
      expect(pushback.kind).toBe('pushback');
      expect(pushback.summary).toBe("No, that's too complicated. Three steps."); // the human's own words only
      expect(pushback.metadata).toEqual({
        threadId: 't1',
        priorProposal: 'Here is a 14-step rollout with a phased canary, feature flags per region and a weekly review board.',
        context: '[In response to proposal: Here is a 14-step rollout with a phased canary, feature flags per region and a weekly review board.]',
      });
      expect(JSON.stringify({ ...pushback, metadata: undefined })).not.toMatch(/rollout|canary/);

      // Only the message right after the assistant turn answers it; the first prompt and a second consecutive one have no proposal.
      expect(byText('Plan the launch').metadata).toEqual({ threadId: 't1' });
      expect(byText('Also add').metadata).toEqual({ threadId: 't1' });
    });

    it('clips the snippet to 240 characters, keeps threads apart, and skips tool results and system messages between the turns', async () => {
      const dir = await tempDir();
      const file = path.join(dir, 'c.jsonl');
      const long = 'We could rebuild the whole importer around a plugin system. '.repeat(20);
      await writeFile(
        file,
        jsonl([
          { role: 'assistant', content: long, timestamp: '2026-03-01T10:00:00Z', threadId: 'a' },
          { role: 'assistant', content: 'Thread B proposal.', timestamp: '2026-03-01T10:00:30Z', threadId: 'b' },
          { role: 'tool', content: 'tool output', timestamp: '2026-03-01T10:00:40Z', threadId: 'a' },
          { role: 'user', content: [{ type: 'tool_result', content: 'tool result only' }], timestamp: '2026-03-01T10:00:45Z', threadId: 'a' },
          { role: 'system', content: 'be nice', timestamp: '2026-03-01T10:00:50Z', threadId: 'a' },
          { role: 'user', content: 'Instead of that, just patch the one parser.', timestamp: '2026-03-01T10:01:00Z', threadId: 'a' },
          { role: 'user', content: 'Go with the second option.', timestamp: '2026-03-01T10:02:00Z', threadId: 'b' },
        ]),
      );
      const items = await aiPromptsAdapter.collect({ path: file });
      const a = items.find((i) => i.summary.startsWith('Instead of'))!;
      const prior = (a.metadata as { priorProposal: string }).priorProposal;
      expect(prior.length).toBeLessThanOrEqual(240);
      expect(prior.startsWith('We could rebuild the whole importer')).toBe(true);
      expect(prior.endsWith('…')).toBe(true);
      expect(items.find((i) => i.summary.startsWith('Go with'))!.metadata).toMatchObject({ threadId: 'b', priorProposal: 'Thread B proposal.' });
      expect(items.map((i) => i.summary).join(' ')).not.toMatch(/tool output|tool result only|be nice|rebuild the whole/);
    });

    it('works for wrapped lines, { messages } conversations and mapping exports, and survives the store round trip', async () => {
      const dir = await tempDir();
      const file = path.join(dir, 'c.json');
      await writeFile(
        file,
        JSON.stringify([
          { id: 'conv-1', messages: [{ type: 'assistant', message: { role: 'assistant', content: [{ type: 'text', text: 'Option A is a cron job.' }, { type: 'tool_use', name: 'x' }] } }, { type: 'user', message: { role: 'user', content: "Actually, let's use events." }, timestamp: '2026-04-01T09:00:00Z' }] },
          { mapping: { a: { message: { author: { role: 'assistant' }, content: { parts: ['Export-style proposal.'] } } }, b: { message: { author: { role: 'user' }, content: { parts: ['Nope, too heavy.'] }, create_time: 1775034000 } } } },
        ]),
      );
      const items = await aiPromptsAdapter.collect({ path: file });
      expect(items.find((i) => i.summary.startsWith('Actually'))!.metadata).toMatchObject({ priorProposal: 'Option A is a cron job.' });
      expect(items.find((i) => i.summary.startsWith('Nope'))!.metadata).toMatchObject({ priorProposal: 'Export-style proposal.' });

      const store = new CorpusStore(path.join(dir, 'corpus.jsonl'));
      await collectInto(store, aiPromptsAdapter, { path: file });
      const stored = (await store.load()).find((i) => i.summary.startsWith('Actually'))!;
      expect(stored.metadata).toMatchObject({ priorProposal: 'Option A is a cron job.', context: '[In response to proposal: Option A is a cron job.]' });
      expect(stored.summary).toBe("Actually, let's use events.");
    });

    it('shows the labeled context line in `rufus context` output', async () => {
      const dir = await tempDir();
      const file = path.join(dir, 'c.jsonl');
      await writeFile(file, jsonl([{ role: 'assistant', content: 'A twelve-part migration plan.', timestamp: '2026-05-01T08:00:00Z' }, { role: 'user', content: "No, that's too complicated.", timestamp: '2026-05-01T08:01:00Z' }]));
      const lines: string[] = [];
      const io = { out: (l: string) => void lines.push(l), err: (l: string) => void lines.push(l) };
      await main(['--dir', path.join(dir, 'ws'), 'collect', 'ai-prompts', file], io);
      lines.length = 0;
      await main(['--dir', path.join(dir, 'ws'), 'context', 'complicated'], io);
      expect(lines.join('\n')).toMatch(/too complicated[\s\S]*\[In response to proposal: A twelve-part migration plan\.\]/);
    });
  });
});
