// AI-prompts adapter: what YOU asked, decided and pushed back on in AI chat transcripts, from any tool that exports
// JSON or JSONL. HUMAN-ONLY BY DESIGN: assistant, model, system and tool messages are never imported, so model-written
// prose can never contaminate Rufus's picture of how the human thinks. An entry with no clear "this is the human"
// signal is dropped rather than guessed.
//
// Understood shapes (JSON array, one JSON object, or JSONL):
//   { role: "user", content | text, timestamp, threadId }          flat lines
//   { type: "user_message", text }                                  event-style lines
//   { createdBy: "user", text }                                     author-style lines
//   { type: "user", message: { role: "user", content: [...] } }     wrapped lines (content may be text parts)
//   { threadId, messages: [ ...any of the above... ] }              whole conversations
//   { conversations: [ { messages: [...] } ] } and { mapping: { id: { message } } } exports
import { promises as fs } from 'node:fs';
import { inputFiles } from '../fsutil';
import { clip, limitNewest, parseJsonRecords, stableId, type CollectOptions, type CorpusItem, type SourceAdapter } from '../types';
import { parseVisitTime } from './browser';

export interface AiPromptsOptions extends CollectOptions {
  /** More files or folders to read besides `path`. */
  extraPaths?: string[];
}

export type PromptKind = 'pushback' | 'decision' | 'question' | 'prompt';

const HUMAN_ROLES = new Set(['user', 'human']);
const HUMAN_TYPES = new Set(['user_message', 'user', 'human', 'human_message']);

// Prompt wrappers that tools inject around (or instead of) what the human typed.
const WRAPPER_BLOCKS = /<(system-reminder|environment_context|user-instructions|user_instructions|instructions|command-name|command-message|command-args|local-command-stdout|local-command-stderr|ide_[a-z_]+|attached_files|context)>[\s\S]*?<\/\1>/gi;
const BOILERPLATE_START = /^(caveat: the messages below were generated by the user|\[request interrupted by user|# agents\.md instructions|\[tool_result|<function_results>)/i;

const PUSHBACK: RegExp[] = [
  /(^|[.!?]\s+)(no|nope|nah)\s*[,.!:;-]/i,
  /(^|[.!?]\s+)actually\s*[,:]?\s/i,
  /\bdo(n't| not)\b/i,
  /(^|\W)stop\b/i,
  /\binstead of\b/i,
  /\btoo (complicated|complex)\b/i,
  /\bwrong idea\b/i,
  /\bnot what i\b/i,
];
const DECISION: RegExp[] = [/\blet'?s\b/i, /\bgo with\b/i, /\bwe should\b/i, /\bi want to\b/i];

/** Decision-style tags for one human message. Deterministic, no AI. `pushback` always travels with `correction`. */
export function tagPrompt(text: string): { kind: PromptKind; tags: string[] } {
  const t = text.replace(/[‘’]/g, "'");
  const tags: string[] = [];
  const pushback = PUSHBACK.some((re) => re.test(t));
  if (pushback) tags.push('pushback', 'correction');
  if (DECISION.some((re) => re.test(t))) tags.push('decision');
  if (t.includes('?')) tags.push('question');
  const kind: PromptKind = pushback ? 'pushback' : tags.includes('decision') ? 'decision' : tags.includes('question') ? 'question' : 'prompt';
  return { kind, tags };
}

const lower = (v: unknown): string | undefined => (typeof v === 'string' && v.trim() ? v.trim().toLowerCase() : undefined);

/** True only for a message the human wrote. Any contradicting author signal (e.g. role "assistant") rejects it. */
function isHuman(r: Record<string, unknown>, inner?: Record<string, unknown>): boolean {
  const author = r.author ?? inner?.author;
  const signals = [r.role, r.createdBy, r.created_by, inner?.role, inner?.createdBy, typeof author === 'object' && author ? (author as Record<string, unknown>).role : author].map(lower).filter((s): s is string => !!s);
  if (signals.some((s) => !HUMAN_ROLES.has(s))) return false;
  if (signals.length) return true;
  const type = lower(r.type);
  return type !== undefined && HUMAN_TYPES.has(type);
}

/** The text parts of a message body (a string, text parts, or `{ parts }`). Tool results, images and the like are ignored. */
function bodyText(v: unknown): string {
  if (typeof v === 'string') return v;
  if (Array.isArray(v)) {
    return v
      .map((p) => {
        if (typeof p === 'string') return p;
        if (typeof p !== 'object' || p === null) return '';
        const o = p as Record<string, unknown>;
        const t = lower(o.type);
        if (t && t !== 'text' && t !== 'input_text') return '';
        return typeof o.text === 'string' ? o.text : '';
      })
      .filter(Boolean)
      .join('\n');
  }
  if (typeof v === 'object' && v !== null && Array.isArray((v as Record<string, unknown>).parts)) return bodyText((v as Record<string, unknown>).parts);
  return '';
}

function messageText(r: Record<string, unknown>, inner?: Record<string, unknown>): string {
  for (const src of [r, inner]) {
    if (!src) continue;
    for (const key of ['content', 'text', 'parts', 'body']) {
      const t = bodyText(src[key]);
      if (t.trim()) return t;
    }
  }
  return '';
}

/** What the human typed, with injected wrapper blocks removed; empty when nothing human is left. */
export function cleanPromptText(raw: string): string {
  const t = raw.replace(WRAPPER_BLOCKS, ' ').replace(/\s+/g, ' ').trim();
  return BOILERPLATE_START.test(t) ? '' : t;
}

interface Thread {
  id?: string;
}

function timeOf(r: Record<string, unknown>, inner?: Record<string, unknown>): number | undefined {
  for (const src of [r, inner]) {
    if (!src) continue;
    for (const key of ['timestamp', 'created_at', 'createdAt', 'create_time', 'time', 'ts', 'date', 'sentAt', 'sent_at']) {
      const at = parseVisitTime(src[key]);
      if (at !== undefined) return at;
    }
  }
  return undefined;
}

interface Found {
  text: string;
  thread?: string;
  at?: number;
}

function walk(node: unknown, thread: Thread, out: Found[], depth = 0): void {
  if (depth > 6) return;
  if (Array.isArray(node)) {
    for (const n of node) walk(n, thread, out, depth + 1);
    return;
  }
  if (typeof node !== 'object' || node === null) return;
  const r = node as Record<string, unknown>;
  const id = [r.threadId, r.thread_id, r.conversationId, r.conversation_id, r.sessionId, r.session_id, r.id].find((v) => typeof v === 'string' && v) as string | undefined;

  if (Array.isArray(r.messages) || Array.isArray(r.conversations) || (typeof r.mapping === 'object' && r.mapping !== null)) {
    const next: Thread = { id: id ?? thread.id };
    if (Array.isArray(r.messages)) walk(r.messages, next, out, depth + 1);
    if (Array.isArray(r.conversations)) walk(r.conversations, next, out, depth + 1);
    if (typeof r.mapping === 'object' && r.mapping !== null) {
      for (const v of Object.values(r.mapping as Record<string, unknown>)) {
        const m = (v as Record<string, unknown> | null)?.message;
        if (m) walk(m, next, out, depth + 1);
      }
    }
    return;
  }

  const inner = typeof r.message === 'object' && r.message !== null && !Array.isArray(r.message) ? (r.message as Record<string, unknown>) : undefined;
  if (!isHuman(r, inner)) return;
  const text = cleanPromptText(messageText(r, inner));
  if (!text) return;
  const own = [r.threadId, r.thread_id, r.conversationId, r.conversation_id, r.sessionId, r.session_id].find((v) => typeof v === 'string' && v) as string | undefined;
  out.push({ text, thread: own ?? thread.id, at: timeOf(r, inner) });
}

/** Human-authored prompts from parsed transcript records. Assistant, system and tool messages are never returned. */
export function humanPrompts(records: unknown[]): Found[] {
  const out: Found[] = [];
  walk(records, {}, out);
  return out;
}

export const aiPromptsAdapter: SourceAdapter<AiPromptsOptions> = {
  id: 'ai-prompts',
  source: 'ai-prompts',
  async collect(options: AiPromptsOptions): Promise<CorpusItem[]> {
    const files = (await Promise.all([options.path, ...(options.extraPaths ?? [])].map((p) => inputFiles(p, ['.json', '.jsonl', '.ndjson'])))).flat();
    const items = new Map<string, CorpusItem>();
    for (const file of files) {
      const [text, stat] = await Promise.all([fs.readFile(file, 'utf8'), fs.stat(file)]);
      let records: unknown[];
      try {
        records = parseJsonRecords(text).records;
      } catch (err) {
        throw new Error(`Could not read ${file}: ${(err as Error).message}`);
      }
      for (const m of humanPrompts(records)) {
        const at = m.at ?? stat.mtimeMs;
        const { kind, tags } = tagPrompt(m.text);
        // Stable identity: same thread + same words (+ same stated time) is the same prompt, however often it is collected.
        const id = stableId('aiprompt', m.thread ?? '', m.text.toLowerCase(), m.at === undefined ? '' : new Date(m.at).toISOString());
        if (items.has(id)) continue;
        items.set(id, {
          id,
          source: 'ai-prompts',
          kind,
          summary: clip(m.text, 500),
          timestamp: new Date(at).toISOString(),
          ...(tags.length ? { tags } : {}),
          ...(m.thread ? { metadata: { threadId: m.thread } } : {}),
        });
      }
    }
    return limitNewest([...items.values()], options.limit);
  },
};
